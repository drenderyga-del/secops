BEGIN;

-- 1. Create the new partitioned job_reports table with compact columns
CREATE TABLE job_reports_new (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repository_id INTEGER NOT NULL REFERENCES repositories(id) ON DELETE CASCADE,
    job_name      VARCHAR(100) NOT NULL,
    job_status    SMALLINT     NOT NULL,
    pipeline_url  VARCHAR(255),
    ref           VARCHAR(120),
    finished_at   TIMESTAMPTZ  NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT NOW()
) PARTITION BY RANGE (finished_at);

-- Default partition (create additional monthly partitions after migration)
CREATE TABLE job_reports_default PARTITION OF job_reports_new DEFAULT;

-- 2. Create a companion table for raw payloads / extended details
CREATE TABLE job_report_details (
    job_report_id INTEGER PRIMARY KEY REFERENCES job_reports_new(id) ON DELETE CASCADE,
    raw_payload   JSONB,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Copy existing data into the new structure (maps textual enums to compact ints)
INSERT INTO job_reports_new (id, repository_id, job_name, job_status, pipeline_url, ref, finished_at, created_at)
SELECT
    id,
    repository_id,
    LEFT(job_name, 100),
    CASE job_status
        WHEN 'success'  THEN 1
        WHEN 'failed'   THEN 2
        WHEN 'running'  THEN 3
        WHEN 'cancelled' THEN 4
        WHEN 'skipped'  THEN 5
        ELSE 2
    END AS job_status,
    LEFT(pipeline_url, 255),
    LEFT(ref, 120),
    finished_at,
    COALESCE(created_at, finished_at, NOW())
FROM job_reports
ORDER BY id;

-- 4. Sync the identity/sequence
SELECT setval(pg_get_serial_sequence('job_reports_new', 'id'), (SELECT COALESCE(MAX(id), 1) FROM job_reports_new));

-- 5. Swap the tables
ALTER TABLE job_reports RENAME TO job_reports_old;
ALTER TABLE job_reports_new RENAME TO job_reports;
-- 6. Recreate supporting sequence + defaults
DROP SEQUENCE IF EXISTS job_reports_id_seq;
CREATE SEQUENCE job_reports_id_seq OWNED BY job_reports.id;
SELECT setval('job_reports_id_seq', (SELECT COALESCE(MAX(id), 1) FROM job_reports));
ALTER TABLE job_reports ALTER COLUMN id SET DEFAULT nextval('job_reports_id_seq');

-- 7. Create new indexes optimised for lookups
CREATE INDEX idx_job_reports_repo ON job_reports (repository_id, job_name, ref, finished_at DESC);
CREATE INDEX idx_job_reports_status ON job_reports (job_status, finished_at DESC);
CREATE INDEX idx_job_report_details_created_at ON job_report_details (created_at);

-- 8. Optionally drop the legacy enum type if it exists
DROP TYPE IF EXISTS jobstatus CASCADE;
DROP TYPE IF EXISTS job_status CASCADE;

COMMIT;

