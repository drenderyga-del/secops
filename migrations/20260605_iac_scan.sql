BEGIN;

ALTER TABLE products ADD COLUMN IF NOT EXISTS asoc_product_slug VARCHAR;
ALTER TABLE products ADD COLUMN IF NOT EXISTS asoc_product_id VARCHAR;
ALTER TABLE products ADD COLUMN IF NOT EXISTS asoc_sync_status VARCHAR(32);

CREATE TABLE IF NOT EXISTS iac_scan_runs (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status VARCHAR(32) NOT NULL DEFAULT 'queued',
    trigger VARCHAR(32) NOT NULL DEFAULT 'manual',
    target_url VARCHAR NOT NULL,
    gitlab_base_url VARCHAR NOT NULL,
    scope_path VARCHAR NOT NULL,
    scanner_name VARCHAR(64) NOT NULL DEFAULT 'checkov',
    total_repositories INTEGER NOT NULL DEFAULT 0,
    candidate_repositories INTEGER NOT NULL DEFAULT 0,
    scanned_repositories INTEGER NOT NULL DEFAULT 0,
    uploaded_repositories INTEGER NOT NULL DEFAULT 0,
    findings_count INTEGER NOT NULL DEFAULT 0,
    summary_json TEXT,
    error_text TEXT,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS iac_scan_repositories (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES iac_scan_runs(id) ON DELETE CASCADE,
    product_id INTEGER REFERENCES products(id) ON DELETE SET NULL,
    repository_id INTEGER REFERENCES repositories(id) ON DELETE SET NULL,
    gitlab_project_id INTEGER NOT NULL,
    project_path VARCHAR NOT NULL,
    project_url VARCHAR,
    default_branch VARCHAR,
    clone_url VARCHAR,
    has_iac BOOLEAN NOT NULL DEFAULT FALSE,
    iac_markers TEXT,
    finder_status VARCHAR(32) NOT NULL DEFAULT 'queued',
    scan_status VARCHAR(32) NOT NULL DEFAULT 'queued',
    asoc_upload_status VARCHAR(32) NOT NULL DEFAULT 'pending',
    asoc_product_slug VARCHAR,
    asoc_product_id VARCHAR,
    sarif_path VARCHAR,
    critical_count INTEGER NOT NULL DEFAULT 0,
    high_count INTEGER NOT NULL DEFAULT 0,
    medium_count INTEGER NOT NULL DEFAULT 0,
    low_count INTEGER NOT NULL DEFAULT 0,
    info_count INTEGER NOT NULL DEFAULT 0,
    findings_count INTEGER NOT NULL DEFAULT 0,
    error_text TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS iac_scan_findings (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id INTEGER NOT NULL REFERENCES iac_scan_runs(id) ON DELETE CASCADE,
    scan_repository_id INTEGER NOT NULL REFERENCES iac_scan_repositories(id) ON DELETE CASCADE,
    product_id INTEGER REFERENCES products(id) ON DELETE SET NULL,
    repository_id INTEGER REFERENCES repositories(id) ON DELETE SET NULL,
    project_path VARCHAR NOT NULL,
    project_url VARCHAR,
    severity VARCHAR(16) NOT NULL,
    rule_id VARCHAR(160) NOT NULL,
    title VARCHAR NOT NULL,
    description TEXT,
    recommendation TEXT,
    file_path VARCHAR,
    line INTEGER,
    evidence TEXT,
    scanner_name VARCHAR(64) NOT NULL DEFAULT 'checkov',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_iac_scan_runs_status ON iac_scan_runs(status);
CREATE INDEX IF NOT EXISTS idx_iac_scan_runs_scope ON iac_scan_runs(scope_path);
CREATE INDEX IF NOT EXISTS idx_iac_scan_repos_run ON iac_scan_repositories(run_id);
CREATE INDEX IF NOT EXISTS idx_iac_scan_repos_project_path ON iac_scan_repositories(project_path);
CREATE INDEX IF NOT EXISTS idx_iac_scan_repos_scan_status ON iac_scan_repositories(scan_status);
CREATE INDEX IF NOT EXISTS idx_iac_scan_repos_asoc_status ON iac_scan_repositories(asoc_upload_status);
CREATE INDEX IF NOT EXISTS idx_iac_scan_findings_repo ON iac_scan_findings(scan_repository_id);
CREATE INDEX IF NOT EXISTS idx_iac_scan_findings_severity ON iac_scan_findings(severity);
CREATE INDEX IF NOT EXISTS idx_iac_scan_findings_rule ON iac_scan_findings(rule_id);

COMMIT;
