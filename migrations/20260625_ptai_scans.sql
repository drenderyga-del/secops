BEGIN;

-- Async PT AI scans are triggered fire-and-forget by the GitLab `ptai_scan`
-- job (POST /ext/v1/scan/ to Vampy/ASOC). The GitLab job ends immediately, so
-- its duration tells us nothing about the real scan. We capture the ASOC ids
-- printed in the job trace and poll ASOC for the actual scan-pipeline status.
CREATE TABLE IF NOT EXISTS ptai_scans (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    gitlab_project_id INTEGER NOT NULL,
    gitlab_pipeline_id INTEGER NOT NULL,
    gitlab_job_id INTEGER NOT NULL UNIQUE,
    repository_id INTEGER REFERENCES repositories(id) ON DELETE SET NULL,
    product_id INTEGER REFERENCES products(id) ON DELETE SET NULL,
    asoc_scan_id VARCHAR,
    asoc_task_id VARCHAR,
    asoc_pipeline_id VARCHAR,
    repo_slug VARCHAR,
    branch VARCHAR,
    -- ASOC ScanPipelineStatus (PENDING/IN_PROGRESS/ERROR/SUCCESS/PARTIAL_SUCCESS)
    -- plus our own sentinels PENDING (initial) and TRIGGER_FAILED (no ids in trace).
    asoc_status VARCHAR(32) NOT NULL DEFAULT 'PENDING',
    trigger_failed BOOLEAN NOT NULL DEFAULT FALSE,
    job_web_url VARCHAR,
    error_text TEXT,
    last_polled_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    last_alert_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT NOW(),
    updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ix_ptai_scans_status ON ptai_scans (asoc_status);

COMMIT;
